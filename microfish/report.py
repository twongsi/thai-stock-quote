"""Stage 4 -- render the swarm into an interactive report."""

from __future__ import annotations

from .simulator import SimulationResult

_EMOJI = {"bullish": "🟢", "bearish": "🔴", "neutral": "⚪"}


def render_report(result: SimulationResult) -> str:
    """Produce a human-readable Markdown report from a simulation result."""
    snap = result.snapshot
    lines: list[str] = []

    lines.append(f"# MiroFish forecast — {snap.ticker}")
    lines.append("")
    lines.append(
        f"_As of {snap.as_of} · last close {snap.last_close:.2f} · "
        f"horizon {result.horizon_weeks} weeks · {len(result.agents)} analysts · "
        f"{len(result.rounds) - 1} debate round(s)_"
    )
    lines.append("")

    # Headline consensus.
    emoji = _EMOJI.get(result.consensus_stance, "⚪")
    lines.append("## Consensus")
    lines.append("")
    lines.append(
        f"{emoji} **{result.consensus_stance.upper()}** · "
        f"confidence {result.consensus_confidence:.0%} · "
        f"expected move {result.consensus_target_pct:+.1f}% · "
        f"panel agreement {result.agreement:.0%}"
    )
    lines.append("")

    # Snapshot facts.
    lines.append("## Market snapshot")
    lines.append("")
    lines.append("```")
    lines.append(snap.to_facts())
    lines.append("```")
    lines.append("")

    # Final stances table.
    lines.append("## Analyst panel (final round)")
    lines.append("")
    lines.append("| Analyst | View | Conf. | Target | Rationale |")
    lines.append("|---|---|---:|---:|---|")
    for s in sorted(result.final_round, key=lambda x: -x.signed_confidence):
        e = _EMOJI.get(s.stance, "⚪")
        rationale = s.rationale.replace("|", "\\|").replace("\n", " ")
        lines.append(
            f"| {s.agent} | {e} {s.stance} | {s.confidence:.0%} | "
            f"{s.target_change_pct:+.1f}% | {rationale} |"
        )
    lines.append("")

    # Debate evolution (only if there was a debate).
    if len(result.rounds) > 1:
        lines.append("## How the debate moved the panel")
        lines.append("")
        first = {s.agent: s for s in result.rounds[0]}
        last = {s.agent: s for s in result.rounds[-1]}
        changed = False
        for name, s0 in first.items():
            s1 = last.get(name)
            if s1 and s1.stance != s0.stance:
                changed = True
                lines.append(
                    f"- **{name}** shifted {s0.stance} → {s1.stance}: {s1.rationale}"
                )
        if not changed:
            lines.append("- No analyst changed direction; the panel held its initial views.")
        lines.append("")

    lines.append("---")
    lines.append(
        "_Generated by MiroFish for stocks — a multi-agent simulation. "
        "Not investment advice._"
    )
    return "\n".join(lines)
